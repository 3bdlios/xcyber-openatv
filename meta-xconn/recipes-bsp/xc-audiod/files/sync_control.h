#ifndef XC_SYNC_CONTROL_H
#define XC_SYNC_CONTROL_H
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
/* 90kHz timestamp differences must be signed across the 32-bit wrap. */
static int32_t xc_delta(uint32_t a,uint32_t b){return (int32_t)(a-b);}
/* Persist clock readiness while consuming stale audio at decoder speed. */
struct xc_start_clock {int valid,advancing;uint32_t p,v;int64_t t,last_v;};
static int xc_start_ready(struct xc_start_clock *s,int64_t ms,uint32_t p,uint32_t v){
 if(!s->valid){s->valid=1;s->p=p;s->v=v;s->t=s->last_v=ms;return 0;}
 int64_t dt=ms-s->t;int32_t dp=xc_delta(p,s->p),dv=xc_delta(v,s->v);
 if(dt<0||dt>1500||dp<0||llabs((int64_t)dp-dt*90)>27000||dv>180000||dv<-180000){
  memset(s,0,sizeof(*s));return 0;
 }
 if(dv)s->last_v=ms;
 if(dp>0)s->advancing= s->advancing<2?s->advancing+1:2;
 s->p=p;s->v=v;s->t=ms;
 if(ms-s->last_v>250){s->advancing=0;return 0;}
 return s->advancing>=2 && llabs((int64_t)xc_delta(p,v))<=90000;
}
struct xc_sync {int valid,n,agree,sign,values[9],ppm;uint32_t p,v;int64_t t,last_v;};
static int xc_cmp(const void *a,const void *b){int x=*(const int*)a,y=*(const int*)b;return (x>y)-(x<y);}
/* Return 1 for a new soft-rate request, -1 to cancel it, 0 for no change.
 * No output samples are dropped or silence generated by this controller. */
static int xc_observe(struct xc_sync *s,int64_t ms,uint32_t p,uint32_t v,uint32_t a){
 if(!s->valid){s->valid=1;s->p=p;s->v=v;s->t=s->last_v=ms;return 0;}
 int64_t dt=ms-s->t;int32_t dp=xc_delta(p,s->p),dv=xc_delta(v,s->v);
 if(dv)s->last_v=ms;
 s->p=p;s->v=v;s->t=ms;
 if(dt<=0||dt>1500||dp<0||llabs((int64_t)dp-dt*90)>27000||ms-s->last_v>250||dv>180000||dv<-180000){
  s->n=s->agree=s->sign=0;s->ppm=0;return -1;
 }
 int32_t err=xc_delta(p,a);
 if(llabs((int64_t)err)>180000){s->n=s->agree=0;s->ppm=0;return -1;}
 s->values[s->n++]=err;
 if(s->n<9)return 0;
 s->n=0;qsort(s->values,9,sizeof(int),xc_cmp);int med=s->values[4];
 if(s->values[7]-s->values[1]>7200){s->agree=0;s->ppm=0;return -1;}
 int sign=med>2250?1:med<-2250?-1:0;
 if(!sign){s->agree=s->sign=0;s->ppm=0;return -1;}
 s->agree=sign==s->sign?s->agree+1:1;s->sign=sign;
 if(s->agree<3)return 0;
 /* Correct over ten seconds, limited to +/-0.5%. Positive error means
  * audio is late: fewer output samples (negative compensation). */
 int ppm=-(int)((int64_t)med*1000000/(90000*10));
 if(ppm>5000)ppm=5000;if(ppm<-5000)ppm=-5000;
 s->ppm=ppm;return 1;
}
#endif
